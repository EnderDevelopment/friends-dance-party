public class FriendsRemoteCommand implements CommandExecutor {
    @Override
    public boolean onCommand(CommandSender sender, Command command, String label, String[] args) {
        if (sender instanceof Player) {
            Player player = (Player) sender;
            // Toggle Friends Doll states logic here
            player.sendMessage("Friends Remote has been used!");
            return true;
        }
        return false;
    }
}